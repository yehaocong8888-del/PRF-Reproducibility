    "                    B_base=b[\"criteria\"][\"same_base_image\"][\"score\"],\n",
    "                    B_instance=b[\"criteria\"][\"same_instance\"][\"score\"],\n",
    "                    B_strong=b[\"criteria\"][\"strong_structure\"][\"score\"],\n",
    "                    B_weak=b[\"criteria\"][\"weak_structure\"][\"score\"],\n",
    "                    B_decision=b[\"final\"], B_conf=f'{float(b[\"conf\"]):.3f}',\n",
    "                    C_noise=c[\"noise\"], C_cover_raw=f'{float(c[\"cover_raw\"]):.4f}', C_cover_cap=f'{float(c[\"cover_cap\"]):.4f}',\n",
    "                    C_clip_raw=f'{float(c[\"raw\"]):.4f}', C_clip_masked=f'{float(c[\"masked\"]):.4f}', C_delta=f'{float(c[\"delta\"]):.4f}',\n",
    "                    C_decision=c[\"decision\"], C_explain=c[\"explain\"],\n",
    "                )\n",
    "\n",
    "                t = call_teacher(user)\n",
