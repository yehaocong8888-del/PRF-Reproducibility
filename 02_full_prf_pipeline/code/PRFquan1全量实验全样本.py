    "            {\"role\": \"system\", \"content\": D_SYSTEM_PROMPT},\n",
    "            {\"role\": \"user\", \"content\": user_prompt},\n",
    "        ],\n",
    "        \"temperature\": 0.0,\n",
    "    }\n",
    "    j = request_json(LLM_30B_URL, payload, TIMEOUT_30B, RETRY_30B)\n",
    "    msg = j[\"choices\"][0][\"message\"][\"content\"]\n",
    "    obj = extract_json(msg)\n",
    "    if obj.get(\"schema\") != \"prf_teacher_arbitration_v1\":\n",
    "        raise ValueError(f\"bad teacher schema: {obj.get('schema')}\")\n",
    "    if obj[\"final_decision\"] not in [\"ACCEPT\",\"REJECT\",\"AMBIGUOUS\"]:\n",
    "        raise ValueError(\"bad teacher final_decision\")\n",
    "    # adopted/overruled sanity (light)\n",
    "    if set(obj.get(\"adopted_from\", [])) & set(obj.get(\"overruled\", [])):\n",
    "        raise ValueError(\"teacher adopted_from intersects overruled\")\n",
    "    return obj\n",
    "\n",
    "def step_teacher():\n",
    "    done = read_done_set(T_DONE)\n",
    "    print(f\"[T] resume done={len(done)}\")\n",
    "    total = 0\n",
    "    # count disputes first for progress bar\n",
    "    with DISPUTE.open(\"r\", encoding=\"utf-8\") as <LOCAL_DRIVE_F>\n",
    "        for line in <LOCAL_DRIVE_F>\n",
    "            if line.strip():\n",
    "                total += 1\n",
    "\n",
    "    pbar = tqdm(desc=\"Teacher 30B (disputes)\", total=total, ncols=100)\n",
    "\n",
    "    with DISPUTE.open(\"r\", encoding=\"utf-8\") as fr, T_OUT.open(\"a\", encoding=\"utf-8\") as fw, T_DONE.open(\"a\", encoding=\"utf-8\") as fd:\n",
    "        for line in fr:\n",
    "            if not line.strip():\n",
    "                continue\n",
    "            j = json.loads(line)\n",
    "            qid = safe_int(j[\"query_image_id\"]); cid = safe_int(j[\"candidate_image_id\"])\n",
