    "                    else:\n",
    "                        c_decision = \"AMBIGUOUS\"\n",
    "                        c_explain = \"未观察到噪声导致的强反证（或噪声不存在）\"\n",
    "\n",
    "                    out = {\n",
    "                        \"schema\": \"c_noise_maskclip_v4\",\n",
    "                        \"query_image_id\": it[\"query_image_id\"],\n",
    "                        \"candidate_image_id\": it[\"candidate_image_id\"],\n",
