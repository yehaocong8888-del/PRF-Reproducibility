    "        pts = p.get(\"points\", [])\n",
    "        if len(pts) < 3:\n",
    "            raise ValueError(\"polygon needs >=3 points\")\n",
    "\n",
    "def mask_image_with_polys(img: Image.Image, polys):\n",
    "    if not polys:\n",
    "        return img, 0.0\n",
    "    w, h = img.size\n",
    "    mask = Image.new(\"L\", (w, h), 0)\n",
    "    draw = ImageDraw.Draw(mask)\n",
    "    for poly in polys:\n",
    "        pts_xy = [(float(x)*w, float(y)*h) for x, y in poly[\"points\"]]\n",
    "        draw.polygon(pts_xy, fill=255)\n",
    "    out = img.copy()\n",
    "    out.paste((0,0,0), mask=mask)\n",
    "    cover = float(np.array(mask).mean()/255.0)\n",
    "    return out, cover\n",
    "\n",
    "def decide_A(sim: float) -> str:\n",
    "    if sim >= 0.90: return \"SUPPORT\"\n",
    "    if sim >= 0.80: return \"WEAK\"\n",
    "    return \"AGAINST\"\n",
    "\n",
    "def vote_from_A(a_dec: str) -> str:\n",
    "    if a_dec == \"SUPPORT\": return \"ACCEPT\"\n",
    "    if a_dec == \"AGAINST\": return \"REJECT\"\n",
    "    return \"AMBIGUOUS\"\n",
    "\n",
    "def vote_from_B(b_final: str) -> str:\n",
    "    return b_final\n",
    "\n",
    "def vote_from_C(c_obj: dict) -> str:\n",
    "    # C defaults neutral; only strong counter-evidence votes REJECT\n",
    "    if c_obj[\"C_decision\"] == \"REJECT\":\n",
    "        return \"REJECT\"\n",
    "    return \"AMBIGUOUS\"\n",
    "\n",
    "def two_of_three(v1: str, v2: str, v3: str) -> Optional[str]:\n",
    "    # Only return definite majority for ACCEPT/REJECT\n",
    "    cnt = { \"ACCEPT\":0, \"REJECT\":0, \"AMBIGUOUS\":0 }\n",
    "    for v in [v1,v2,v3]:\n",
    "        cnt[v] += 1\n",
    "    if cnt[\"ACCEPT\"] >= 2: return \"ACCEPT\"\n",
    "    if cnt[\"REJECT\"] >= 2: return \"REJECT\"\n",
    "    return None\n",
    "\n",
