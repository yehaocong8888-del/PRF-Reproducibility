    "        with torch.no_grad():\n",
    "            feats = model.get_image_features(**inputs)\n",
    "            feats = feats / feats.norm(dim=-1, keepdim=True)\n",
    "            sim = float((feats[0] * feats[1]).sum().item())\n",
    "        return sim\n",
    "\n",
