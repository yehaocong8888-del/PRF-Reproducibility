    "                        \"cover_frac_capped\": safe_float(cover_cap),\n",
    "                        \"mask_clip_raw\": safe_float(sim_raw),\n",
    "                        \"mask_clip_masked\": safe_float(sim_masked),\n",
    "                        \"mask_clip_delta\": safe_float(delta),\n",
    "                        \"C_decision\": c_decision,\n",
    "                        \"C_explain\": c_explain,\n",
    "                    }\n",
    "\n",
    "                    fw.write(json.dumps(out, ensure_ascii=False) + \"\\n\")\n",
    "                    fd.write(k + \"\\n\")\n",
    "                    done.add(k)\n",
    "\n",
    "                except Exception as <LOCAL_DRIVE_E>\n",
    "                    append_fail(C_FAIL, {\n",
    "                        \"when\": now_iso(), \"stage\": \"C\", \"key\": k,\n",
    "                        \"query_path\": it[\"query_path\"], \"candidate_path\": it[\"candidate_path\"],\n",
    "                        \"error\": str(e)\n",
    "                    })\n",
    "                    if FAIL_FAST_GLOBAL:\n",
    "                        raise\n",
    "\n",
    "                pbar.update(1)\n",
    "    finally:\n",
    "        pbar.close()\n",
    "    print(f\"[C] done -> {C_OUT}\")\n",
    "\n",
