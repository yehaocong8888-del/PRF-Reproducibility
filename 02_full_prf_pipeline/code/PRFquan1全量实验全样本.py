    "def summarize_jsonl(path: Path, key_fields=(\"final_decision\",), limit=None):\n",
    "    cnt = {}\n",
    "    n = 0\n",
    "    if not path.exists():\n",
    "        return {\"n\": 0}\n",
    "    with path.open(\"r\", encoding=\"utf-8\") as <LOCAL_DRIVE_F>\n",
    "        for line in <LOCAL_DRIVE_F>\n",
    "            if not line.strip():\n",
    "                continue\n",
    "            j = json.loads(line)\n",
    "            n += 1\n",
    "            for k in key_fields:\n",
    "                v = j.get(k)\n",
    "                if v is None:\n",
    "                    continue\n",
    "                cnt[str(v)] = cnt.get(str(v), 0) + 1\n",
    "            if limit and n >= limit:\n",
    "                break\n",
    "    return {\"n\": n, \"dist\": cnt}\n",
